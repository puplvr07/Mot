"""Convert the photos in assets/ into web-sized webp files and write assets/photos.js.

Each entry maps a photo slot id in index.html to a source photo. Edit PICKS to change
which photo goes where, then run:  python tools/photos.py
(needs: pip install pillow pillow-heif)
"""
import json, os
from PIL import Image, ImageOps
import pillow_heif

pillow_heif.register_heif_opener()
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
A = os.path.join(ROOT, 'assets')
OUT = os.path.join(A, 'photos')
INTRO = 'inyto'
STRIP = 'inyto/drive-download-20261126T061134Z-1-001'
M1 = 'month 1/drive-download-20261126T061226Z-1-001'
M2 = 'month 2/drive-download-20261126T061521Z-1-001'
M3 = 'month 3/drive-download-20261126T061634Z-1-001'
M46 = 'month 4-6/drive-download-20261126T061731Z-1-001'

# slot id -> source file. p{i}_f{j} = month i+1, frame j (max 3 frames per month).
PICKS = {
    # introduction
    'cover_heart': f'{INTRO}/heart.JPG',
    'cover_a': f'{INTRO}/IMG_4187.HEIC',
    'cover_b': f'{INTRO}/IMG_4191.HEIC',
    'intro_s0': f'{STRIP}/IMG_4211.JPG',
    'intro_s1': f'{STRIP}/IMG_4212.JPG',
    'intro_s2': f'{STRIP}/IMG_4213.JPG',
    'intro_s3': f'{STRIP}/IMG_4214.JPG',
    # month 1
    'p0_f0': f'{M1}/IMG_0547.HEIC', 'p0_f1': f'{M1}/IMG_0630.HEIC', 'p0_f2': f'{M1}/IMG_0746.HEIC',
    # month 2
    'p1_f0': f'{M2}/IMG_1527.HEIC', 'p1_f1': f'{M2}/IMG_1662.HEIC', 'p1_f2': f'{M2}/IMG_1672.HEIC',
    # month 3
    'p2_f0': f'{M3}/IMG_2451.HEIC', 'p2_f1': f'{M3}/IMG_2732.HEIC', 'p2_f2': f'{M3}/IMG_2740.HEIC',
    # months 4-6
    'p3_f0': f'{M46}/9b97aab1310a75b8846f999209cb434a.JPEG', 'p3_f1': f'{M46}/IMG_0038.HEIC', 'p3_f2': f'{M46}/IMG_0042.HEIC',
    'p4_f0': f'{M46}/IMG_4183.HEIC', 'p4_f1': f'{M46}/IMG_4184.HEIC', 'p4_f2': f'{M46}/IMG_4186.HEIC',
    'p5_f0': f'{M46}/IMG_9715.HEIC', 'p5_f1': f'{M46}/att.63u33Dhr72iF_IrPETiYhWJwKs8Hbt34vQqk786N8gg.JPG',
    'p5_f2': f'{M46}/att.zsD2AToffPktrw-wbDN2vWIGHw-CFmFz-fRXOMnQgPU.JPG',
}
# conclusion page: the month 4-6 photos not used above
PICKS.update({
    'out_a': f'{M46}/IMG_4192.HEIC',
    'out_b': f'{M46}/IMG_4185.HEIC',
    'out_c': f'{M46}/IMG_4193.HEIC',
    'out_d': f'{M46}/att.prjs08BynDQjAJLcrIpRt60bqmdKwluF9QP05whdxT8.JPG',   # LensBooth strip
    'out_e': f'{M46}/att.DkSO0-xn0P3nKGhdsHvTwb9e6JwqEcSsPF_if_5iymY.JPG',
    'out_f': f'{M46}/IMG_4188.HEIC',
    'out_g': f'{M46}/IMG_4189.HEIC',
    'out_h': f'{M46}/IMG_2277.HEIC',   # lace heart on the back cover
})
MAXPX = {'out_d': 1600,'cover_heart': 1800}   # the heart is the biggest photo on screen

os.makedirs(OUT, exist_ok=True)
out = {}
for sid, rel in PICKS.items():
    im = ImageOps.exif_transpose(Image.open(os.path.join(A, rel))).convert('RGB')
    m = MAXPX.get(sid, 1200)
    im.thumbnail((m, m), Image.LANCZOS)
    im.save(os.path.join(OUT, sid + '.webp'), 'WEBP', quality=86, method=6)
    out[sid] = f'assets/photos/{sid}.webp'
    print(sid, im.size)
with open(os.path.join(A, 'photos.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by tools/photos.py\nwindow.PHOTOS=' + json.dumps(out) + ';\n')
